public class V_ou_F {
    public static void main(String[] args) {
        boolean valor1 = true;
        boolean valor2 = false;
        boolean valor3 = true;

        if (valor1) {
            System.out.println("Valor 1 é verdadeiro");
        } else {
            System.out.println("Valor 1 é falso");
        }

        if (valor2) {
            System.out.println("Valor 2 é verdadeiro");
        } else {
            System.out.println("Valor 2 é falso");
        }

        if (valor3) {
            System.out.println("Valor 3 é verdadeiro");
        } else {
            System.out.println("Valor 3 é falso");
        }
    }
}